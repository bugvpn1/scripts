#!/usr/bin/env bash
#
# setup-dante.sh — install & configure a Dante SOCKS5 proxy (user/password auth).
#
# Usage:
#   sudo ./setup-dante.sh [--port PORT] [--iface IFACE] [--allow CIDR[,CIDR...]]
#                         [--creds-file PATH] [--no-force-ipv4]
#
# Examples:
#   sudo ./setup-dante.sh
#   sudo ./setup-dante.sh --port 1080 --allow 203.0.113.0/24,198.51.100.7/32
#   sudo ./setup-dante.sh --iface ens3 --creds-file ./proxy.txt
#
# Notes:
#   * socksmethod is "username": a random username and password are generated
#     on every run, created as a no-login system user, printed to stdout and
#     saved to --creds-file (default ./dante-credentials.txt in the current
#     directory, mode 600, owned by the user who ran sudo).
#   * Only the generated user may use the proxy; other system accounts are
#     rejected. --allow still limits which client IPs may connect at all.
#   * Idempotent: re-running updates the config, replaces the previously
#     generated proxy user with a fresh one, and restarts the service.
#   * Forces IPv4 by default: sets glibc resolver precedence so Dante never
#     tries a dead IPv6 route for hostname targets (SOCKS reply code 8).
#     Disable with --no-force-ipv4 if this box has real IPv6 egress.

set -euo pipefail

PORT=1080
IFACE=""
ALLOW="0.0.0.0/0"
FORCE_IPV4=1
CONF=/etc/danted.conf
CREDS_FILE="./dante-credentials.txt"
USER_TAG="dante-proxy"   # GECOS marker so re-runs only delete users we created

# ---- parse args -------------------------------------------------------------
while [[ $# -gt 0 ]]; do
  case "$1" in
    --port)  PORT="$2"; shift 2 ;;
    --iface) IFACE="$2"; shift 2 ;;
    --allow) ALLOW="$2"; shift 2 ;;
    --creds-file) CREDS_FILE="$2"; shift 2 ;;
    --no-force-ipv4) FORCE_IPV4=0; shift ;;
    -h|--help)
      sed -n '2,25p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "Unknown arg: $1" >&2; exit 1 ;;
  esac
done

# ---- preflight --------------------------------------------------------------
if [[ $EUID -ne 0 ]]; then
  echo "Please run as root (sudo)." >&2
  exit 1
fi

if ! command -v apt-get >/dev/null 2>&1; then
  echo "This script targets Debian/Ubuntu (apt). Adapt the install step otherwise." >&2
  exit 1
fi

# ---- detect external interface ---------------------------------------------
if [[ -z "$IFACE" ]]; then
  IFACE=$(ip route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="dev"){print $(i+1); exit}}')
fi
if [[ -z "$IFACE" ]] || ! ip link show "$IFACE" >/dev/null 2>&1; then
  echo "Could not determine external interface. Pass one with --iface." >&2
  echo "Available: $(ls /sys/class/net | tr '\n' ' ')" >&2
  exit 1
fi
echo ">> Using interface: $IFACE"
echo ">> Listening port:  $PORT"
echo ">> Allowed clients: $ALLOW"

# ---- install ----------------------------------------------------------------
echo ">> Installing dante-server..."
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq dante-server

# ---- build client pass rules from ALLOW ------------------------------------
CLIENT_RULES=""
IFS=',' read -ra CIDRS <<< "$ALLOW"
for cidr in "${CIDRS[@]}"; do
  cidr="$(echo "$cidr" | xargs)"   # trim whitespace
  [[ -z "$cidr" ]] && continue
  CLIENT_RULES+="client pass {
    from: ${cidr} to: 0.0.0.0/0
    log: connect disconnect error
}
"
done

# ---- generate proxy credentials ---------------------------------------------
# gen_rand LEN CHARSET — read /dev/urandom in fixed chunks (no SIGPIPE under
# pipefail) until we have LEN characters from CHARSET.
gen_rand() {
  local len=$1 chars=$2 out=""
  while (( ${#out} < len )); do
    out+=$(head -c 256 /dev/urandom | LC_ALL=C tr -dc "$chars")
  done
  printf '%s' "${out:0:len}"
}

# Remove the user generated by a previous run (only if we created it).
if [[ -f "$CREDS_FILE" ]]; then
  OLD_USER=$(awk -F= '$1=="USERNAME"{print $2}' "$CREDS_FILE")
  if [[ -n "$OLD_USER" ]] && [[ "$(getent passwd "$OLD_USER" | cut -d: -f5)" == "$USER_TAG" ]]; then
    userdel "$OLD_USER" 2>/dev/null || true
    echo ">> Removed previous proxy user: $OLD_USER"
  fi
fi

# Letters+digits only, so the credentials are safe inside socks5://user:pass@ URLs.
PROXY_USER="u$(gen_rand 9 'a-z0-9')"
PROXY_PASS="$(gen_rand 24 'A-Za-z0-9')"

useradd --system --no-create-home --shell /usr/sbin/nologin --comment "$USER_TAG" "$PROXY_USER"
echo "${PROXY_USER}:${PROXY_PASS}" | chpasswd
echo ">> Created proxy user: $PROXY_USER"

# ---- write config -----------------------------------------------------------
if [[ -f "$CONF" ]] && [[ ! -f "${CONF}.orig" ]]; then
  cp "$CONF" "${CONF}.orig"
  echo ">> Backed up original config to ${CONF}.orig"
fi

echo ">> Writing $CONF"
cat > "$CONF" <<EOF
# Managed by setup-dante.sh — edits may be overwritten on re-run.
logoutput: syslog /var/log/danted.log

internal: 0.0.0.0 port = ${PORT}
external: ${IFACE}

socksmethod: username
clientmethod: none

user.privileged: root
user.unprivileged: nobody

${CLIENT_RULES}
socks pass {
    from: 0.0.0.0/0 to: 0.0.0.0/0
    socksmethod: username
    user: ${PROXY_USER}
    log: connect disconnect error
}

socks block {
    from: 0.0.0.0/0 to: 0.0.0.0/0
    log: connect error
}
EOF

# ---- force IPv4 -------------------------------------------------------------
# Dante hands hostname targets to the system resolver. If that returns an IPv6
# (AAAA) address and this box has no IPv6 egress, Dante fails with SOCKS reply
# code 8 ("address type not supported"). Bumping IPv4 precedence in gai.conf
# makes getaddrinfo() return IPv4 first, so Dante connects over IPv4.
if [[ "$FORCE_IPV4" -eq 1 ]]; then
  GAI=/etc/gai.conf
  MARK="precedence ::ffff:0:0/96  100"
  touch "$GAI"
  if grep -qxF "$MARK" "$GAI" 2>/dev/null; then
    echo ">> IPv4 precedence already set in $GAI"
  else
    printf '\n# Added by setup-dante.sh: prefer IPv4 for hostname resolution\n%s\n' "$MARK" >> "$GAI"
    echo ">> Set IPv4 precedence in $GAI"
  fi
fi

# ---- start ------------------------------------------------------------------
echo ">> Enabling and (re)starting danted..."
systemctl enable danted >/dev/null 2>&1 || true
systemctl restart danted

sleep 1
if systemctl is-active --quiet danted; then
  echo ">> danted is running."
else
  echo "!! danted failed to start. Recent logs:" >&2
  journalctl -u danted -n 30 --no-pager >&2 || true
  exit 1
fi

# ---- verify -----------------------------------------------------------------
SERVER_IP=$(ip -4 -o addr show dev "$IFACE" | awk '{split($4,a,"/"); print a[1]; exit}')
echo ">> Self-test through the proxy (hostname target, resolver-decided)..."
if command -v curl >/dev/null 2>&1; then
  # No -4 here on purpose: this exercises the same resolution path Dante uses
  # for hostname targets, so it catches the IPv6 problem instead of hiding it.
  if OUT=$(curl -s --max-time 10 --socks5-hostname "127.0.0.1:${PORT}" \
             --proxy-user "${PROXY_USER}:${PROXY_PASS}" https://ifconfig.me 2>/dev/null); then
    echo ">> Proxy egress IP: ${OUT}"
    [[ -n "$OUT" ]] && SERVER_IP="$OUT"
  else
    echo "!! Self-test failed. If FORCE_IPV4 was disabled, an IPv6-only path is" >&2
    echo "   the likely cause (SOCKS reply code 8). Re-run without --no-force-ipv4." >&2
  fi
fi

# ---- save & show credentials -----------------------------------------------
SERVER_IP="${SERVER_IP:-<server-ip>}"
PROXY_URL="socks5://${PROXY_USER}:${PROXY_PASS}@${SERVER_IP}:${PORT}"

( umask 077
  cat > "$CREDS_FILE" <<EOF
# Dante SOCKS5 credentials — generated by setup-dante.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
HOST=${SERVER_IP}
PORT=${PORT}
USERNAME=${PROXY_USER}
PASSWORD=${PROXY_PASS}
URL=${PROXY_URL}
EOF
)
chmod 600 "$CREDS_FILE"
# Under sudo, hand the file back to the invoking user so they can read it.
if [[ -n "${SUDO_USER:-}" ]]; then
  chown "$SUDO_USER": "$CREDS_FILE"
fi

cat <<EOF

Done. SOCKS5 proxy listening on port ${PORT}.

  Host:     ${SERVER_IP}
  Port:     ${PORT}
  Username: ${PROXY_USER}
  Password: ${PROXY_PASS}
  URL:      ${PROXY_URL}

Credentials saved to ${CREDS_FILE} (mode 600).

Test from a client:
  curl --proxy "socks5h://${PROXY_USER}:${PROXY_PASS}@${SERVER_IP}:${PORT}" https://ifconfig.me

Note: a new user/password is generated on every run; the previous one stops
working. Consider restricting inbound TCP :${PORT} with --allow or a firewall.
EOF
